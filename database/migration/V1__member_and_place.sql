COMMENT ON TABLE user_preferences IS 'Per-user travel style preferences';
COMMENT ON TABLE places IS 'Searchable travel places';
COMMENT ON TABLE place_images IS 'Place image metadata';
COMMENT ON TABLE place_travel_styles IS 'Travel style relevance tags for places';
COMMENT ON TABLE favorites IS 'Places saved by users';
