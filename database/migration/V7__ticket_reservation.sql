CREATE TABLE reservation_items (
    reservation_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id      BIGINT NOT NULL REFERENCES reservations(reservation_id) ON DELETE CASCADE,
    ticket_time_slot_id BIGINT NOT NULL REFERENCES ticket_time_slots(ticket_time_slot_id),
    product_name        VARCHAR(150) NOT NULL,
    option_name         VARCHAR(150) NOT NULL,
    usage_date          DATE NOT NULL,
    usage_start_time    TIME,
    quantity            SMALLINT NOT NULL CHECK (quantity > 0),
    unit_price          NUMERIC(15,2) NOT NULL CHECK (unit_price >= 0),
    line_amount         NUMERIC(15,2) NOT NULL CHECK (line_amount >= 0),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_reservation_items_slot UNIQUE (reservation_id, ticket_time_slot_id),
    CONSTRAINT ck_reservation_items_line_amount CHECK (line_amount = unit_price * quantity)
);
CREATE INDEX idx_reservation_items_slot ON reservation_items(ticket_time_slot_id);

