CREATE TABLE ticket_products (
    ticket_product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id          BIGINT NOT NULL REFERENCES places(place_id),
    name              VARCHAR(150) NOT NULL,
    description       TEXT,
    sale_start_at     TIMESTAMPTZ NOT NULL,
    sale_end_at       TIMESTAMPTZ NOT NULL,
    usage_start_date  DATE NOT NULL,
    usage_end_date    DATE NOT NULL,
    status            VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_ticket_products_sale_period CHECK (sale_end_at > sale_start_at),
    CONSTRAINT ck_ticket_products_usage_period CHECK (usage_end_date >= usage_start_date),
    CONSTRAINT ck_ticket_products_status CHECK (status IN ('DRAFT', 'ON_SALE', 'SOLD_OUT', 'ENDED', 'CANCELLED'))
);
CREATE INDEX idx_ticket_products_place_status ON ticket_products(place_id, status);
CREATE INDEX idx_ticket_products_sale_period ON ticket_products(sale_start_at, sale_end_at);
CREATE TRIGGER trg_ticket_products_updated_at BEFORE UPDATE ON ticket_products
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE ticket_product_options (
    ticket_product_option_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_product_id        BIGINT NOT NULL REFERENCES ticket_products(ticket_product_id) ON DELETE CASCADE,
    name                     VARCHAR(150) NOT NULL,
    description              VARCHAR(1000),
    unit_price               NUMERIC(15,2) NOT NULL CHECK (unit_price >= 0),
    currency_code            CHAR(3) NOT NULL DEFAULT 'KRW',
    max_quantity_per_user    SMALLINT NOT NULL DEFAULT 4 CHECK (max_quantity_per_user > 0),
    sort_order               SMALLINT NOT NULL DEFAULT 1 CHECK (sort_order > 0),
    is_active                BOOLEAN NOT NULL DEFAULT TRUE,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ticket_product_options_name UNIQUE (ticket_product_id, name),
    CONSTRAINT uk_ticket_product_options_order UNIQUE (ticket_product_id, sort_order)
);
CREATE TRIGGER trg_ticket_product_options_updated_at BEFORE UPDATE ON ticket_product_options
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE ticket_time_slots (
    ticket_time_slot_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_product_option_id  BIGINT NOT NULL REFERENCES ticket_product_options(ticket_product_option_id) ON DELETE CASCADE,
    usage_date                DATE NOT NULL,
    start_time                TIME,
    end_time                  TIME,
    status                    VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    created_at                TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ticket_time_slots UNIQUE NULLS NOT DISTINCT (ticket_product_option_id, usage_date, start_time),
    CONSTRAINT ck_ticket_time_slots_period CHECK (end_time IS NULL OR start_time IS NULL OR end_time > start_time),
    CONSTRAINT ck_ticket_time_slots_status CHECK (status IN ('OPEN', 'CLOSED', 'CANCELLED'))
);
CREATE INDEX idx_ticket_time_slots_date_status ON ticket_time_slots(usage_date, status);
CREATE TRIGGER trg_ticket_time_slots_updated_at BEFORE UPDATE ON ticket_time_slots
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE ticket_inventory (
    ticket_time_slot_id BIGINT PRIMARY KEY REFERENCES ticket_time_slots(ticket_time_slot_id) ON DELETE CASCADE,
    total_quantity      INTEGER NOT NULL CHECK (total_quantity >= 0),
    reserved_quantity   INTEGER NOT NULL DEFAULT 0 CHECK (reserved_quantity >= 0),
    version             BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_ticket_inventory_quantities CHECK (reserved_quantity <= total_quantity)
